const express = require("express");
const { protect } = require("../middleware/authMiddleware");
const { authorizeRoles } = require("../middleware/roleMiddleware");
const { createIncident, getCustomerIncidents, getAdminIncidents, updateIncident, getMyProtection, getMyReliability, getDriverReliability, updateDriverReward, getPaymentProtection, getFareTransparency, getMyRewards, getDriverRewardLedger, getAdminFareTransparency } = require("../controllers/rideGuardController");
const router = express.Router();
router.post("/incidents", protect, authorizeRoles("customer", "driver", "admin", "superadmin"), createIncident);
router.get("/my", protect, authorizeRoles("customer"), getMyProtection);
router.get("/incidents/my", protect, authorizeRoles("customer"), getCustomerIncidents);
router.get("/reliability/me", protect, authorizeRoles("driver"), getMyReliability);
router.get("/rewards/me", protect, authorizeRoles("driver"), getMyRewards);
router.get("/rewards/:driverId/ledger", protect, authorizeRoles("admin", "superadmin"), getDriverRewardLedger);
router.get("/reliability/:driverId", protect, authorizeRoles("admin", "superadmin"), getDriverReliability);
router.patch("/rewards/:driverId", protect, authorizeRoles("admin", "superadmin"), updateDriverReward);
router.get("/payment-protection/:tripId", protect, authorizeRoles("customer"), getPaymentProtection);
router.get("/fare-transparency/:bookingId", protect, authorizeRoles("customer"), getFareTransparency);
router.get("/admin/fare-transparency", protect, authorizeRoles("admin", "superadmin"), getAdminFareTransparency);
router.get("/admin/incident-center", protect, authorizeRoles("admin", "superadmin"), getAdminIncidents);
router.get("/admin/incidents", protect, authorizeRoles("admin", "superadmin"), getAdminIncidents);
router.get("/incidents", protect, authorizeRoles("admin", "superadmin"), getAdminIncidents);
router.patch("/incidents/:id", protect, authorizeRoles("admin", "superadmin"), updateIncident);
module.exports = router;
